
import { askGemini } from '../src/lib/ai/gemini.js';
import 'dotenv/config';

async function testExtractionLogic() {
    const sampleText = `
        Объявлены победители 118-го набора Радара. 
        Первое место занял Haskimail, сервис транзакционных рассылок. 
        Второе место у UCHUUCHU, приложения для обучения под интересы пользователя. 
        Третье место досталось MOLL Y/X, расширению для маскировки данных в чатах с ИИ.
        
        Напоминаем, что в понедельник в 18:00 будет стрим с победителями!
    `;

    const prompt = `
        Действуй как профессиональный ИИ-аналитик стартапов и венчурный скаут. 
        Твоя задача: найти ПРИКЛАДНЫЕ бизнес-идеи, конкретные стартапы или новые инструменты.
        
        СТРОГИЕ ПРАВИЛА:
        1. ФИЛЬТРАЦИЯ: Игнорируй только "пустую" информацию: анонсы будущих стримов, поздравления ("Стартап-привет"), информацию об изменениях условий работы сообществ или просто ссылки без описания.
        2. АТОМАРНОСТЬ: Если в тексте подборка (например, "Топ-5 проектов"), ОБЯЗАТЕЛЬНО ВЫДЕЛИ КАЖДЫЙ ПРОЕКТ В ОТДЕЛЬНЫЙ ОБЪЕКТ. 
        3. ПРИКЛАДНАЯ ЦЕННОСТЬ: Ищи конкретные продукты, фичи, инструменты автоматизации, боты или кейсы заработка. Даже если проект маленький, но прикладной — он нам нужен.
        
        Требования к каждой найденной идее:
        - title: Название самого стартапа/продукта (до 10 слов, на русском). Постарайся извлечь именно название.
        - summary: Максимально прикладное описание (3-5 предложений): Что делает? Какую задачу решает? Как на этом заработать (или какова модель)? 
        
        ОТВЕТЬ ТОЛЬКО В ФОРМАТЕ JSON (МАССИВ ОБЪЕКТОВ):
        [
          { "title": "Название", "summary": "Детальное описание..." }
        ]
        
        Если в тексте нет абсолютно ничего конкретного — верни [].
        
        ТЕКСТ:
        """${sampleText}"""
    `;

    console.log('--- Testing Extraction ---');
    try {
        const response = await askGemini(prompt);
        console.log('Raw Result:', response);
    } catch (e) {
        console.error('Error:', e);
    }
}

testExtractionLogic();
